/**
 * A `.docs-light` scope: the light values of every token the library's `.dark` class
 * overrides, so one preview can show light while the page is dark (`.dark` on a preview does
 * the opposite). Read from the library's token files, so it follows them.
 *
 * Output: src/generated/light-scope.css
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { generatedDir, library } from './paths.mjs';

const tokens = join(library, 'src/styles/tokens');
const declarations = (file) =>
  new Map(
    [...readFileSync(join(tokens, file), 'utf8').matchAll(/^\s*(--[\w-]+)\s*:\s*([^;]+);/gm)].map(
      ([, name, value]) => [name, value.trim()],
    ),
  );

const dark = new Set([
  ...declarations('theme-dark-tokens.css').keys(),
  ...declarations('theme-dark-semantic.css').keys(),
]);
const light = new Map([
  ...declarations('theme-light-tokens.css'),
  ...declarations('theme-light-semantic.css'),
]);

const lines = [...light].filter(([name]) => dark.has(name)).map(([n, v]) => `  ${n}: ${v};`);
writeFileSync(
  join(generatedDir, 'light-scope.css'),
  `/* Generated by scripts/gen-light-scope.mjs. */\n.docs-light {\n  color-scheme: light;\n${lines.join('\n')}\n}\n`,
);
console.log(`light scope: ${lines.length} tokens`);
